# 2. Student Busy Commitments & Schedule Storage
EXISTING_COMMITMENTS = {
    "2026-11-23": ["College Lab (09:00 - 13:00)", "Project Meeting (16:00 - 17:00)"],
    "2026-11-25": ["Seminar Presentation (10:00 - 12:00)"],
}

SAVED_STUDY_PLAN = []

# 3. Define Agent Tools
def calculate_study_capacity(start_date: str, exam_date: str, daily_hours: float) -> str:
    """Calculates the total days and available study hours between start_date and exam_date."""
    try:
        start = datetime.strptime(start_date, "%Y-%m-%d")
        exam = datetime.strptime(exam_date, "%Y-%m-%d")
        days_left = (exam - start).days

        if days_left <= 0:
            return "Error: Exam date must be after the start date."

        total_hours = days_left * daily_hours
        return (
            f"Days available: {days_left} days (from {start_date} to {exam_date}, leaving exam day free).\n"
            f"Total study capacity: {total_hours} hours at {daily_hours} hrs/day."
        )
    except ValueError:
        return "Error: Dates must be in YYYY-MM-DD format."

def get_busy_schedule(date: str) -> str:
    """Checks if the student has existing college classes, labs, or events on a specific date."""
    events = EXISTING_COMMITMENTS.get(date, [])
    if not events:
        return f"{date}: Completely free (no fixed commitments)."
    return f"{date} Busy Events: {', '.join(events)}"

def save_daily_task(date: str, topic: str, duration_hours: float, task_type: str) -> str:
    """Saves a study or revision block into the student's official study plan."""
    SAVED_STUDY_PLAN.append({
        "date": date,
        "topic": topic,
        "duration_hours": duration_hours,
        "type": task_type
    })
    return f"Saved: [{date}] {topic} ({duration_hours} hrs - {task_type})"

def get_current_plan() -> str:
    """Returns all currently saved study tasks in chronological order."""
    if not SAVED_STUDY_PLAN:
        return "The study plan is currently empty."

    sorted_plan = sorted(SAVED_STUDY_PLAN, key=lambda x: x["date"])
    lines = [
        f"- {item['date']}: {item['topic']} ({item['duration_hours']} hrs | {item['type']})"
        for item in sorted_plan
    ]
    return "Current Saved Study Plan:\n" + "\n".join(lines)

def clear_future_plan(from_date: str) -> str:
    """Removes all scheduled tasks on or after `from_date` so they can be cleanly rescheduled."""
    global SAVED_STUDY_PLAN
    removed = [t for t in SAVED_STUDY_PLAN if t["date"] >= from_date]
    SAVED_STUDY_PLAN = [t for t in SAVED_STUDY_PLAN if t["date"] < from_date]

    if not removed:
        return f"No tasks found on or after {from_date}."

    removed_summary = ", ".join([f"{t['topic']} ({t['duration_hours']}h)" for t in removed])
    return f"Cleared {len(removed)} tasks from {from_date} onwards. Topics still to schedule: {removed_summary}"

# 4. Configure the Study Plan Scheduler Agent
agent_config = types.GenerateContentConfig(
    system_instruction=(
        "You are an adaptive Study Plan & Revision Scheduler Agent for students.\n"
        "Workflow for creating a new plan:\n"
        "1. Call `calculate_study_capacity` and `get_busy_schedule` for each day.\n"
        "2. Assign lighter study hours on days that have busy college commitments.\n"
        "3. Prioritize difficult topics early and reserve the day before the exam for Revision/Mock Test.\n"
        "4. Save each session using `save_daily_task`.\n\n"
        "Workflow when a student misses a day:\n"
        "1. Call `get_current_plan` to see scheduled topics.\n"
        "2. Call `clear_future_plan` from the missed date onward.\n"
        "3. Re-check `calculate_study_capacity` and `get_busy_schedule` for the remaining days.\n"
        "4. Redistribute all remaining topics fairly and save them using `save_daily_task`."
    ),
    tools=[
        calculate_study_capacity,
        get_busy_schedule,
        save_daily_task,
        get_current_plan,
        clear_future_plan,
    ],
    temperature=0.2,
)

# 5. Execution Loop with Retry Handling
def run_study_planner(user_request: str, retries: int = 3):
    print("\nProcessing with AI Agent...\n" + "-" * 60)

    for attempt in range(retries):
        try:
            response = client.models.generate_content(
                model="gemini-3.8-flash",
                contents=user_request,
                config=agent_config,
            )
            print(f"Study Plan Agent:\n{response.text}\n")
            return
        except ServerError as e:
            if e.code == 503 and attempt < retries - 1:
                wait_time = 2 ** attempt
                print(f"Server busy (503). Retrying in {wait_time}s...")
                time.sleep(wait_time)
            else:
                raise

